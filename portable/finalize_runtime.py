"""Rewrite CPython build configuration and wheel entry points for relocation."""

import importlib.metadata
import os
import runpy
import sys
from pathlib import Path


def relocate_config(runtime: Path) -> None:
    config_module, = (runtime / "lib/python3.11").glob("_sysconfigdata_*.py")
    variables = runpy.run_path(str(config_module))["build_time_vars"]
    source_prefix = variables["prefix"]
    if source_prefix != "/install":
        variables = {
            key: value.replace(source_prefix, "/install")
            if isinstance(value, str) else value
            for key, value in variables.items()
        }
    config_module.write_text(
        "# Generated by portable/finalize_runtime.py.\n"
        "import sys\n\n"
        f"build_time_vars = {variables!r}\n"
        "build_time_vars = {\n"
        "    key: value.replace('/install', sys.base_prefix)\n"
        "    if isinstance(value, str) else value\n"
        "    for key, value in build_time_vars.items()\n"
        "}\n"
    )
    for path in config_module.parent.glob(
        f"__pycache__/{config_module.stem}.*.pyc"
    ):
        path.unlink()


def relocate_entry_points(runtime: Path) -> None:
    prefix = (
        "#!/bin/sh\n"
        "'''exec' \"$(dirname -- \"$(realpath -- \"$0\")\")/python\" -s \"$0\" \"$@\"\n"
        "' '''\n"
    )
    site = runtime / "lib/python3.11/site-packages"
    for dist in importlib.metadata.distributions(path=[str(site)]):
        for entry in dist.entry_points:
            if entry.group not in {"console_scripts", "gui_scripts"}:
                continue
            path = runtime / "bin" / entry.name
            function = entry.attr.split(".", 1)[0]
            path.write_text(
                prefix
                + "import sys\n"
                + f"from {entry.module} import {function}\n\n"
                + 'if __name__ == "__main__":\n'
                + f"    sys.exit({entry.attr}())\n"
            )
            path.chmod(0o755)


def check_prefix(runtime: Path) -> None:
    if sys.version_info[:2] != (3, 11) or Path(sys.base_prefix).resolve() != runtime:
        raise SystemExit("Run finalization using the target runtime's Python.")
    for path in runtime.rglob("*"):
        if not path.is_symlink():
            continue
        target = path.resolve()
        if not target.is_relative_to(runtime):
            raise SystemExit(f"Runtime contains an external symlink: {path} -> {target}")
        if not target.exists():
            raise SystemExit(f"Runtime contains a dangling symlink: {path} -> {target}")
        if path.readlink().is_absolute():
            path.unlink()
            path.symlink_to(os.path.relpath(target, path.parent))
    for path in (runtime / "lib/python3.11/site-packages").glob("*.egg-link"):
        raise SystemExit(f"Runtime contains an editable install: {path}")


def main() -> None:
    runtime = Path(sys.base_prefix).resolve()
    check_prefix(runtime)
    relocate_config(runtime)
    relocate_entry_points(runtime)
    marker = runtime / "lib/python3.11/EXTERNALLY-MANAGED"
    marker.write_text(
        "[externally-managed]\n"
        "Error=Rebuild the bundled RLinf runtime using portable/build_runtime.sh.\n"
    )


if __name__ == "__main__":
    main()
